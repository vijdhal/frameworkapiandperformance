"""
TestHub Automation Studio — Security Testing engine (OWASP ZAP).

Emits a ZAP **Automation Framework plan** — the tool's own declarative YAML
format — rather than a bespoke wrapper script. That matters for two reasons:
the plan is auditable by a client security team who already know ZAP, and it
runs identically from the CLI, Docker or a Jenkins stage without TestHub in the
execution path.

Scope is API security: an OpenAPI import (or explicit URL set), passive scan,
then an active scan gated by an alert threshold that fails the build.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

from .base import ACCEL, SPEC_DIR_DEFAULT, Assets, Row, field, register, section

# OWASP API Security Top 10 (2023) — the vocabulary a client's security review
# will expect to see mapped, rather than a generic "we scanned it".
API_TOP10 = [
    ('API1', 'Broken Object Level Authorization'),
    ('API2', 'Broken Authentication'),
    ('API3', 'Broken Object Property Level Authorization'),
    ('API4', 'Unrestricted Resource Consumption'),
    ('API5', 'Broken Function Level Authorization'),
    ('API6', 'Unrestricted Access to Sensitive Business Flows'),
    ('API7', 'Server Side Request Forgery'),
    ('API8', 'Security Misconfiguration'),
    ('API9', 'Improper Inventory Management'),
    ('API10', 'Unsafe Consumption of APIs'),
]

# Which of the above ZAP can meaningfully probe unaided. The rest need business
# context a scanner does not have; saying so is more useful than implying full
# coverage.
ZAP_AUTOMATABLE = {'API2', 'API4', 'API7', 'API8', 'API9'}


def _safe(s: str) -> str:
    return ''.join(c for c in str(s or '').strip() if c.isalnum() or c in '-_') or 'asset'


def _js(s) -> str:
    """Quote for embedding in TypeScript. json.dumps is exact for this."""
    return json.dumps(str(s))


def _yq(s) -> str:
    return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'


def _ortoni_wrapper(asset: str, service: str, cfg: dict, plan_rel: str) -> str:
    """A Playwright spec that runs the ZAP plan and asserts its gate.

    Same join as the performance engine: ZAP is a Java process and cannot report
    into Ortoni, so Playwright runs it, reads the summary ZAP itself writes, and
    turns the gate into tests. Security then appears in the release report next
    to the functional suites rather than as an HTML file somebody has to be told
    to open.

    The authorisation reference is asserted first and deliberately: a security
    run that cannot say what authorised it should not be reported as evidence at
    all, and putting that check in the suite means it travels with the artifact.
    """
    summary = f'zap-summary-{asset}-{service}.json'
    plan = f'{asset}-{service}.zap.yaml'
    auth = str(cfg.get('authorisationRef') or '').strip()

    return '\n'.join([
        "import { test, expect } from '@playwright/test';",
        "import { execFileSync } from 'child_process';",
        "import * as fs from 'fs';",
        "import * as path from 'path';",
        '',
        '/**',
        f' * {asset} — {service} · security gate (OWASP ZAP)',
        ' *',
        ' * GENERATED by TestHub Automation Studio.',
        ' *',
        ' * Runs the ZAP Automation Framework plan and asserts its gate as Playwright',
        ' * tests, so the scan lands in the Ortoni report with everything else. ZAP\'s own',
        ' * HTML and JSON are still written beside it — this is the summary view, not a',
        ' * replacement for the tool\'s evidence.',
        ' */',
        '',
        '// One repo-relative value drives both. Previously PLAN was resolved against',
        "// process.cwd() while ZAP ran with cwd: WORK_DIR, so setting ZAP_DIR — the only",
        '// knob that pointed at the plan — always produced a path that did not exist,',
        '// and the resulting "Cannot access file" was swallowed into a skip.',
        f'const PLAN = path.resolve(process.env.ZAP_PLAN ?? {_js(plan_rel)});',
        f'const SUMMARY = {_js(summary)};',
        'const WORK_DIR = path.dirname(PLAN);',
        f'const AUTHORISATION = {_js(auth)};',
        "const ZAP = process.env.ZAP_BIN ?? '/Applications/ZAP.app/Contents/Java/zap.sh';",
        '',
        'let summary: any = null;',
        "let skipReason = '';",
        '',
        f"test.describe('@Security {asset} — {service}', () => {{",
        '',
        '  test.beforeAll(() => {',
        '    if (!fs.existsSync(PLAN)) {',
        "      skipReason = `ZAP plan not found at ${PLAN}. Set ZAP_PLAN.`;",
        '      return;',
        '    }',
        '    if (!fs.existsSync(ZAP)) {',
        "      skipReason = `ZAP not found at ${ZAP} — set ZAP_BIN. Not a failed scan.`;",
        '      return;',
        '    }',
        '    try {',
        '      // PLAN is already absolute. zap.sh resolves a relative path against its',
        '      // own install directory, not the working directory.',
        "      execFileSync(ZAP, ['-cmd', '-autorun', PLAN],",
        "        { cwd: WORK_DIR, stdio: 'pipe', timeout: 30 * 60_000 });",
        '    } catch {',
        '      // A failing gate exits non-zero. The assertions below say which',
        '      // rule failed, which is the part a reviewer needs.',
        '    }',
        '    // ZAP requires summaryFile to be "./"-prefixed (a bare name errors with',
        '    // "parent directory does not exist") but then resolves that "./" against its',
        '    // OWN home, not the working directory — so the report lands beside the',
        '    // binary while the HTML lands here. Look in both rather than reporting a',
        '    // successful scan as "no summary written".',
        '    const candidates = [',
        '      path.join(WORK_DIR, SUMMARY),',
        '      path.join(path.dirname(ZAP), SUMMARY),',
        '      path.join(process.cwd(), SUMMARY),',
        '    ];',
        '    const file = candidates.find((c) => fs.existsSync(c));',
        '    if (!file) {',
        "      skipReason = `ZAP ran but no summary was found. Looked in:\\n  ${candidates.join('\\n  ')}`;",
        '      return;',
        '    }',
        "    summary = JSON.parse(fs.readFileSync(file, 'utf-8'));",
        '    // Leave nothing in the ZAP install directory — it is not ours to write to.',
        '    if (file.startsWith(path.dirname(ZAP))) fs.rmSync(file, { force: true });',
        '  });',
        '',
        "  test('scan was authorised', async () => {",
        '    // Asserted before any result is read. Evidence that cannot name its',
        '    // authorisation is not evidence anyone should act on.',
        "    expect(AUTHORISATION, 'no authorisation reference recorded for this scan')",
        "      .not.toBe('');",
        '  });',
        '',
        "  test('no failing security rules', async () => {",
        '    test.skip(!!skipReason, skipReason);',
        "    expect(summary?.fail ?? 0, 'ZAP reported failing rules').toBe(0);",
        '  });',
        '',
        "  test('scan actually executed rules', async () => {",
        '    test.skip(!!skipReason, skipReason);',
        '    const total = (summary?.pass ?? 0) + (summary?.warn ?? 0) + (summary?.fail ?? 0);',
        "    expect(total, 'ZAP evaluated no rules — the plan or target is wrong')",
        '      .toBeGreaterThan(0);',
        '  });',
        '',
        '});',
        '',
    ])


class SecurityZapEngine:
    id = 'sec'
    title = 'Security Testing'
    emits_assets = True

    # macOS installs ZAP as an .app bundle, so `which zap.sh` finds nothing even
    # though ZAP is present. Check the bundle too before declaring it missing.
    BUNDLE_PATHS = (
        '/Applications/ZAP.app/Contents/Java/zap.sh',
        '/Applications/OWASP ZAP.app/Contents/Java/zap.sh',
    )

    # Windows ships the launcher as zap.bat, so probing only for zap.sh reports
    # "ZAP is not installed" on a machine where it plainly is — the one failure
    # mode this preflight exists to avoid. Same class of bug as the macOS .app
    # bundle above, different platform.
    LAUNCHERS = ('zap.sh', 'zap.bat')

    @staticmethod
    def zap_path() -> str | None:
        for launcher in SecurityZapEngine.LAUNCHERS:
            found = shutil.which(launcher)
            if found:
                return found
        for p in SecurityZapEngine.BUNDLE_PATHS:
            if Path(p).is_file():
                return p
        return None

    @property
    def can_execute(self) -> bool:
        return self.zap_path() is not None

    def preflight(self) -> tuple[bool, str]:
        zap = self.zap_path()
        if zap:
            return True, f'ZAP found at {zap} — plans can be generated and run.'
        if shutil.which('docker'):
            return True, ('ZAP is not installed locally. Plans are generated and can be run with: '
                          'docker run -v $(pwd):/zap/wrk ghcr.io/zaproxy/zaproxy zap.sh '
                          '-cmd -autorun /zap/wrk/<plan>.yaml')
        return True, 'ZAP is not installed. Plans are generated but cannot be run here.'

    def schema(self):
        return [
            section('Authorisation — required before any scan leaves this machine', [
                field('authorisationRef', 'Authorisation reference', width='full', required=True,
                      placeholder='CHG0045821 / signed SOW ref / security approval ID',
                      hint='The signed scope in docs/security-testing-scope.md. An active scan is '
                           'indistinguishable from an attack at the target end; this reference is '
                           'what separates authorised testing from an incident, and it is written '
                           'into the plan so the evidence carries its own permission.'),
                field('authorisedBy', 'Approved by', width='full',
                      placeholder='Name, role — the client person who can authorise testing of this system'),
            ], note='Verbal approval in a stand-up is not authorisation. Neither is a Jira ticket. '
                    'For a target you own — localhost, your own sandbox — write SELF-OWNED and the '
                    'system name.'),
            section('Target', [
                field('assetName', 'Asset Name', required=True, placeholder='clients'),
                field('serviceName', 'Service Name', required=True, placeholder='customer-service'),
                field('baseUrl', 'Target URL', required=True, width='full',
                      placeholder='https://api.example.com/v1'),
                field('openapiUrl', 'OpenAPI spec (URL or path)', width='full',
                      placeholder='contracts/openapi/user.yaml',
                      hint='Given a spec, ZAP explores every declared operation instead of guessing.'),
            ]),
            section('Scan', [
                field('scanType', 'Scan type', 'select',
                      options=['passive-only', 'baseline', 'full-active'], default='baseline'),
                field('maxDuration', 'Max duration (min)', default='10'),
                field('failOn', 'Fail build on', 'select',
                      options=['High', 'Medium', 'Low'], default='Medium'),
                field('maxAlerts', 'Max allowed alerts', default='0'),
            ], note='full-active sends attack traffic — never point it at production.'),
            section('Authentication', [
                field('authHeader', 'Auth header name', placeholder='Authorization'),
                field('authEnvVar', 'Token env var', placeholder='API_TOKEN',
                      hint='Name only. The value is resolved from the environment by ZAP at run time.'),
            ]),
        ]

    def build_matrix(self, cfg: dict) -> list[Row]:
        # Refuse at generate time rather than warn at run time. A plan that exists
        # gets run — by someone who was not in the conversation, months later, from
        # a CI job. Withholding the artifact until the reference is recorded is the
        # only point where a person is still reading the screen.
        if not str(cfg.get('authorisationRef') or '').strip():
            raise ValueError(
                'Authorisation reference required. An active scan is indistinguishable from an '
                'attack at the target end — record the signed scope reference '
                '(docs/security-testing-scope.md), or SELF-OWNED <system> for a target you own.')
        scan = (cfg.get('scanType') or 'baseline').lower()
        rows = [
            Row(name='spider — explore the attack surface', kind='positive',
                detail='Discover endpoints, from the OpenAPI spec when supplied.',
                data={'job': 'spider'}),
            Row(name='passive scan — analyse all traffic', kind='positive',
                detail='Headers, cookies, information disclosure, misconfiguration.',
                data={'job': 'passiveScan'}),
        ]
        if scan in ('baseline', 'full-active'):
            rows.append(Row(name='active scan — probe for vulnerabilities', kind='positive',
                            detail='Injection, traversal, SSRF and related attack classes.',
                            data={'job': 'activeScan'}))
        rows.append(Row(
            name=f"gate — fail on {cfg.get('failOn') or 'Medium'}+ alerts",
            kind='threshold',
            detail=f"Build fails above {cfg.get('maxAlerts') or 0} alert(s) at or over this risk.",
            data={'job': 'gate'}))

        covered = [f'{c} {n}' for c, n in API_TOP10 if c in ZAP_AUTOMATABLE]
        rows.append(Row(name='coverage — OWASP API Top 10', kind='info',
                        detail='Scanner-addressable: ' + ', '.join(c.split()[0] for c in covered) +
                               '. The rest need business context and stay manual.',
                        data={'job': 'coverage'}))
        return rows

    def render(self, cfg: dict, rows: list[Row]) -> Assets:
        asset, service = _safe(cfg.get('assetName')), _safe(cfg.get('serviceName'))
        out_dir = Path((cfg.get('paths') or {}).get('security') or ACCEL['sec'])
        scan = (cfg.get('scanType') or 'baseline').lower()
        target = (cfg.get('baseUrl') or '').rstrip('/')
        spec = (cfg.get('openapiUrl') or '').strip()
        fail_on = cfg.get('failOn') or 'Medium'
        max_alerts = cfg.get('maxAlerts') or '0'
        minutes = cfg.get('maxDuration') or '10'
        # _safe() falls back to 'asset' for empty input, and 'asset' is truthy — so an
        # auth header with no token name emitted a literal `Bearer ${asset}` into the
        # plan, which reads as a configured credential. Guard on the raw value.
        hdr = (cfg.get('authHeader') or '').strip()
        env_var = _safe(cfg.get('authEnvVar')) if str(cfg.get('authEnvVar') or '').strip() else ''

        Y = []
        Y.append('---')
        Y.append(f'# {asset} — {service} · OWASP ZAP Automation Framework plan')
        Y.append('# GENERATED by TestHub Automation Studio.')
        Y.append('#')
        Y.append('# Run locally:   zap.sh -cmd -autorun ' + f'{asset}-{service}.zap.yaml')
        Y.append('# Run in Docker: docker run -v $(pwd):/zap/wrk ghcr.io/zaproxy/zaproxy \\')
        Y.append(f'#                  zap.sh -cmd -autorun /zap/wrk/{asset}-{service}.zap.yaml')
        Y.append('#')
        Y.append('# AUTHORISED UNDER: ' + str(cfg.get('authorisationRef') or '').strip())
        if str(cfg.get('authorisedBy') or '').strip():
            Y.append('# APPROVED BY:     ' + str(cfg.get('authorisedBy')).strip())
        Y.append('# Scope and rules of engagement: docs/security-testing-scope.md')
        Y.append('# Running this against anything outside that scope is not covered by it.')
        Y.append('#')
        Y.append('# No credentials are stored here. Tokens resolve from the environment.')
        Y.append('')
        Y.append('env:')
        Y.append('  contexts:')
        Y.append(f'    - name: {_yq(asset)}')
        Y.append('      urls:')
        Y.append(f'        - {_yq(target)}')
        Y.append('      includePaths:')
        Y.append(f'        - {_yq(target + ".*")}')
        Y.append('      excludePaths: []')
        Y.append('  parameters:')
        Y.append('    failOnError: true')
        Y.append('    failOnWarning: false')
        Y.append('    progressToStdout: true')
        Y.append('')
        Y.append('jobs:')

        if hdr and env_var:
            Y.append('  - type: replacer')
            Y.append('    parameters:')
            Y.append('      deleteAllRules: false')
            Y.append('    rules:')
            Y.append(f'      - description: {_yq("inject auth header")}')
            Y.append('        enabled: true')
            Y.append('        matchType: REQ_HEADER')
            Y.append(f'        matchString: {_yq(hdr)}')
            Y.append(f'        replacementString: {_yq("Bearer ${" + env_var + "}")}')
            Y.append('')

        if spec:
            Y.append('  - type: openapi')
            Y.append('    parameters:')
            if spec.startswith('http'):
                Y.append(f'      apiUrl: {_yq(spec)}')
            else:
                Y.append(f'      apiFile: {_yq(spec)}')
            Y.append(f'      targetUrl: {_yq(target)}')
            Y.append(f'      context: {_yq(asset)}')
            Y.append('')
        else:
            Y.append('  - type: spider')
            Y.append('    parameters:')
            Y.append(f'      context: {_yq(asset)}')
            Y.append(f'      url: {_yq(target)}')
            Y.append(f'      maxDuration: {minutes}')
            Y.append('')

        Y.append('  - type: passiveScan-wait')
        Y.append('    parameters:')
        Y.append('      maxDuration: 5')
        Y.append('')

        if scan in ('baseline', 'full-active'):
            Y.append('  - type: activeScan')
            Y.append('    parameters:')
            Y.append(f'      context: {_yq(asset)}')
            Y.append(f'      maxRuleDurationInMins: {minutes}')
            Y.append(f'      maxScanDurationInMins: {minutes}')
            Y.append(f"      policy: {_yq('Default Policy' if scan == 'baseline' else 'API-Full')}")
            Y.append('')

        Y.append('  # Evidence: both a human report and a machine-readable one.')
        Y.append('  - type: report')
        Y.append('    parameters:')
        Y.append('      template: traditional-html')
        Y.append(f'      reportFile: {_yq(f"zap-report-{asset}-{service}.html")}')
        Y.append('')
        Y.append('  - type: report')
        Y.append('    parameters:')
        Y.append('      template: traditional-json')
        Y.append(f'      reportFile: {_yq(f"zap-report-{asset}-{service}.json")}')
        Y.append('')
        Y.append('  # Gate: per-rule PASS/FAIL/WARN summary, and the CI exit signal.')
        Y.append('  #')
        Y.append('  # summaryFile is REQUIRED and MUST be "./"-prefixed. A bare filename has')
        Y.append('  # no parent directory, and ZAP aborts the entire plan with')
        Y.append('  #   "Job outputSummary parent directory of summaryFile does not exist"')
        Y.append('  # Verified against ZAP 2.17.0 — the plan fails before any report is written.')
        Y.append('  - type: outputSummary')
        Y.append('    parameters:')
        Y.append('      format: Long')
        Y.append(f'      summaryFile: {_yq(f"./zap-summary-{asset}-{service}.json")}')

        # The marker is what makes this file safe to regenerate — engines.write()
        # refuses to clobber anything that lacks it, on the assumption a human
        # wrote it. Without this line the coverage doc could never be reissued.
        readme = [f'# {asset} — {service} · security scan',
                  '<!-- GENERATED by TestHub Automation Studio. -->', '',
                  f'Scan type: **{scan}** · fails on **{fail_on}+** above **{max_alerts}** alert(s).', '',
                  '## OWASP API Security Top 10 coverage', '',
                  '| ID | Risk | Addressed by this scan |', '|---|---|---|']
        for code, name in API_TOP10:
            mark = 'Yes — scanner-addressable' if code in ZAP_AUTOMATABLE else 'No — needs business context, keep manual'
            readme.append(f'| {code} | {name} | {mark} |')
        readme += ['', 'Claiming otherwise would be the kind of coverage theatre a client security',
                   'review exists to catch. The five unmarked risks require knowledge of what the',
                   'business logic *should* permit, which no scanner has.']

        assets = Assets(rows=len(rows), sheet=f'{asset}Sec')
        assets.add(out_dir / f'{asset}-{service}.zap.yaml', '\n'.join(Y) + '\n')
        assets.add(out_dir / f'{asset}-{service}.security-coverage.md', '\n'.join(readme) + '\n')
        # Into testDir, or Playwright never collects it and the security gate is
        # absent from the report rather than green.
        spec_dir = Path((cfg.get('paths') or {}).get('spec') or SPEC_DIR_DEFAULT) / asset
        assets.add(spec_dir / f'{asset}-{service}.zap.spec.ts',
                   _ortoni_wrapper(asset, service, cfg,
                                   str(out_dir / f'{asset}-{service}.zap.yaml')))
        return assets


engine = register(SecurityZapEngine())
